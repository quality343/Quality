/**
 * The clinic's official accounts as a row of icon chips.
 *
 * The platform name is always visible next to the glyph: an icon-only bar
 * leaves older visitors guessing, and the brief explicitly asks that the
 * destination never be conveyed by the icon alone.
 */
export function SocialLinks({
  className = "",
}: {
  className?: string;
}) {
  return (
    <ul className={`flex flex-wrap gap-2 ${className}`}>
      {SOCIAL_LINKS.map((social) => (
        <li key={social.id}>
          <a
            href={social.href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`${social.label} (opens in a new tab)`}
            className="inline-flex min-h-11 items-center gap-2 rounded-full border border-white/15 bg-white/[0.06] px-4 text-sm font-medium text-brand-100 transition-colors hover:border-white/40 hover:bg-white/10 hover:text-white"
          >
            <SocialIcon id={social.id} className="h-4 w-4 shrink-0" />
            {social.label}
          </a>
        </li>
      ))}
    </ul>
  );
}
